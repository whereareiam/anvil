package me.whereareiam.anvil.edition.java.data.block.type;

/**
 * A face of a block, named as vanilla's {@code Direction} names it.
 */
public enum BlockFace {
	/**
	 * The bottom face.
	 */
	DOWN,
	/**
	 * The top face.
	 */
	UP,
	/**
	 * The face toward negative Z.
	 */
	NORTH,
	/**
	 * The face toward positive Z.
	 */
	SOUTH,
	/**
	 * The face toward negative X.
	 */
	WEST,
	/**
	 * The face toward positive X.
	 */
	EAST
}
