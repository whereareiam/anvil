package me.whereareiam.anvil.capability.screen.type;

/**
 * How a boss bar is drawn, named as in Minecraft.
 */
public enum BossBarOverlay {
	/**
	 * One continuous bar.
	 */
	PROGRESS,
	/**
	 * A bar divided into 6 notches.
	 */
	NOTCHED_6,
	/**
	 * A bar divided into 10 notches.
	 */
	NOTCHED_10,
	/**
	 * A bar divided into 12 notches.
	 */
	NOTCHED_12,
	/**
	 * A bar divided into 20 notches.
	 */
	NOTCHED_20
}
