package me.whereareiam.anvil.capability.interaction.type;

/**
 * Face of a block targeted by an interaction.
 */
public enum BlockFace {
	/**
	 * Bottom face.
	 */
	DOWN,
	/**
	 * Top face.
	 */
	UP,
	/**
	 * Negative-Z face.
	 */
	NORTH,
	/**
	 * Positive-Z face.
	 */
	SOUTH,
	/**
	 * Negative-X face.
	 */
	WEST,
	/**
	 * Positive-X face.
	 */
	EAST
}
