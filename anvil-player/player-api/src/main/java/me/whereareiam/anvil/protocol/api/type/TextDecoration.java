package me.whereareiam.anvil.protocol.api.type;

/**
 * A decoration the game draws text with.
 */
public enum TextDecoration {
	/**
	 * Bold text.
	 */
	BOLD,
	/**
	 * Italic text.
	 */
	ITALIC,
	/**
	 * Underlined text.
	 */
	UNDERLINED,
	/**
	 * Text struck through.
	 */
	STRIKETHROUGH,
	/**
	 * Text drawn as changing random characters.
	 */
	OBFUSCATED
}
